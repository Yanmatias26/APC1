#include <stdio.h>

int main(){
    // < menor que
    //<= menor ou igual que
    // > maior
    // >= maior ou igual
    // == igual
    // != diferente
    
    printf("2 eh maior que 5? %i\n",2 > 5);
    printf("2 eh maior igual 5? %i\n", 2 >= 5);
    printf("2 eh menor 5? %i\n", 2< 5);
    printf ("2 eh menor igual 5? %i\n", 2 <= 5);
    printf("2 eh igual 5? %i\n", 2 == 5);
    printf("2 eh diferente 5? %i\n", 2 != 5);

    return 0;
}