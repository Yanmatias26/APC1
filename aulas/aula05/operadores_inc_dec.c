#include <stdio.h>

int main(){
    // ++ incrementa de 1
    // -- decrementa de 1

    int numero = 10;
    printf("Pre-incremento =%i\n", ++numero);
    printf("Pre-decremnto =%i\n", --numero);
    printf("Pos-incremento =%i\n", numero++);
    printf("Pos-decremento =%i\n", numero--);

    return 0;
}